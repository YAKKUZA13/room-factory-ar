import { expect, test } from '@playwright/test';
import { debugState, freshPage, saveManually } from './helpers';

test('the drone demo produces and ships a drone, updates the dashboard and restores progress', async ({ page }) => {
  test.setTimeout(120_000);
  await freshPage(page);
  await page.getByTestId('start-drone-demo').click();
  await expect(page.getByTestId('floor-overview')).toHaveAttribute('aria-pressed', 'true');
  expect((await debugState(page)).production.dronesSold).toBe(0);
  await page.getByTestId('open-production').click();
  const dashboard = page.getByTestId('production-dialog');
  await expect(dashboard).toBeVisible();
  await dashboard.getByRole('button', { name: 'Цепочка дрона' }).click();
  const item = dashboard.getByLabel('Изделие или сырьё');
  await item.selectOption('programmable-board');
  await expect(dashboard.getByRole('button', { name: /Микросхема/ })).toBeVisible();
  await expect(dashboard.getByRole('button', { name: /Провод в изоляции/ })).toBeVisible();
  await dashboard.getByRole('button', { name: /Печатная плата/ }).click();
  await expect(item).toHaveValue('board');
  await expect(dashboard.getByRole('button', { name: /Медная фольга/ })).toBeVisible();
  await dashboard.getByRole('button', { name: /Пластик/ }).click();
  await dashboard.getByRole('button', { name: /Гранулы/ }).click();
  await dashboard.getByRole('button', { name: /Полимерное сырьё/ }).click();
  await expect(dashboard.getByText('Выберите этот ресурс в настройках добытчика.')).toBeVisible();
  await item.selectOption('battery');
  await expect(dashboard.getByRole('button', { name: /Ячейка питания × 2/ })).toBeVisible();
  await dashboard.getByRole('button', { name: 'Показатели' }).click();
  await expect(dashboard.getByRole('heading', { name: 'Ежедневные задания' })).toBeVisible();
  await expect(dashboard.locator('#production-built')).toHaveText(/^[1-9]\d*$/, { timeout: 85_000 });
  await expect(dashboard.locator('#production-sold')).toHaveText(/^[1-9]\d*$/, { timeout: 20_000 });
  await expect(dashboard.getByRole('progressbar', { name: 'Первая поставка дрона' })).toHaveAttribute('value', '1');
  await dashboard.getByRole('button', { name: 'Закрыть' }).click();
  await page.getByTestId('btn-pause').click();
  const snapshot = (await debugState(page)).production;
  await saveManually(page);
  await page.reload();
  await page.getByTestId('continue').click();
  await page.getByTestId('open-production').click();
  await expect(dashboard.locator('#production-sold')).toHaveText(String(snapshot.dronesSold));
  expect((await debugState(page)).production).toEqual(snapshot);
});
